"""The feature atlas: JSON feature records plus a generated inventory.

Layout under config.ATLAS_DIR (env WB_ATLAS_DIR, default <repo>/out/atlas):
  features/<slug>.json     one file per investigated module: {"module": slug, "features": [...]}
  overlaps.json            {"_doc": "...", "mechanics": {"<mechanic>": ["<feature id>", ...]}}
  FEATURE_INVENTORY.md     generated by `inventory`
  auto/<slug>.md           generated by `report`

Record fields, enums and categories are documented in docs/ATLAS.md and defined
in atlas_schema.json. A missing atlas folder simply means zero records.
"""
import glob
import json
import os
import re
from collections import defaultdict

from . import config

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "atlas_schema.json"), encoding="utf-8") as _fh:
    SCHEMA = json.load(_fh)
CATEGORIES = SCHEMA["categories"]
REQUIRED = SCHEMA["required"]
ENUMS = SCHEMA["enums"]


def features_dir():
    return os.path.join(config.ATLAS_DIR, "features")


def overlaps_path():
    return os.path.join(config.ATLAS_DIR, "overlaps.json")


def _read_json(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError) as e:
        raise ValueError("%s: %s" % (path, e))


def _read_feature_file(path):
    d = _read_json(path)
    if not isinstance(d, dict) or not isinstance(d.get("features", []), list) \
            or not all(isinstance(f, dict) for f in d.get("features", [])):
        raise ValueError('%s: expected {"module": ..., "features": [ {record}, ... ]}' % path)
    return d


def _feature_files():
    return sorted(glob.glob(os.path.join(features_dir(), "*.json")))


def _records(d):
    out = []
    for f in d.get("features", []):
        f.setdefault("module", d.get("module"))
        out.append(f)
    return out


def load_all():
    out = []
    for p in _feature_files():
        out.extend(_records(_read_feature_file(p)))
    return out


def validate():
    problems = []
    seen = set()
    recs = []
    for p in _feature_files():
        try:
            recs.extend((p, f) for f in _records(_read_feature_file(p)))
        except ValueError as e:
            problems.append("unreadable file: %s" % e)
    for path, f in recs:
        fid = f.get("id", "?")
        if not isinstance(fid, str):
            problems.append("%s: id must be a string (got %r)" % (os.path.basename(path), fid))
            continue
        if fid in seen:
            problems.append("duplicate id %s" % fid)
        seen.add(fid)
        for k in REQUIRED:
            if k not in f:
                problems.append("%s missing %s" % (fid, k))
        if "category" in f and f["category"] not in CATEGORIES:
            problems.append("%s bad category %r" % (fid, f["category"]))
        for k, allowed in ENUMS.items():
            if k in f and f[k] not in allowed:
                problems.append("%s bad %s %r" % (fid, k, f[k]))
        v = f.get("value")
        if "value" in f and (isinstance(v, bool) or not isinstance(v, int) or not 1 <= v <= 5):
            problems.append("%s bad value %r (need integer 1-5)" % (fid, v))
    return problems


def search(query=None, category=None, module=None):
    rx = re.compile(query, re.I) if query else None
    out = []
    for f in load_all():
        if category and f.get("category") != category:
            continue
        if module and f.get("module") != module:
            continue
        if rx and not rx.search(json.dumps(f)):
            continue
        out.append(f)
    return out


def show(f):
    keys = ["id", "name", "category", "summary", "mechanics", "hooks", "scripts", "menus", "presentations",
            "mission_templates", "dialogs", "slots", "globals", "resources", "native_relation", "target_status",
            "target_evidence", "conflicts", "difficulty", "risk", "value", "recommendation", "confidence",
            "evidence", "overlaps", "notes"]
    lines = []
    for k in keys:
        if k in f and f[k] not in ("", [], {}):
            v = f[k]
            if isinstance(v, list):
                v = ", ".join(str(x) for x in v)
            elif isinstance(v, dict):
                v = "; ".join("%s: %s" % (a, ", ".join(map(str, b)) if isinstance(b, list) else b) for a, b in v.items())
            lines.append("%-17s %s" % (k + ":", v))
    return lines


def load_overlaps():
    d = _read_json(overlaps_path())
    m = d.get("mechanics") if isinstance(d, dict) else None
    if not isinstance(m, dict) or not all(isinstance(v, list) and all(isinstance(x, str) for x in v)
                                       for v in m.values()):
        raise ValueError('%s: expected {"mechanics": {"<name>": ["<feature id>", ...]}}' % overlaps_path())
    return m


def apply_overlaps():
    """Write each feature's `overlaps` from overlaps.json (other ids sharing a
    mechanic). Returns problems (unknown ids). Every file is rebuilt in memory
    before any is written."""
    if not os.path.isfile(overlaps_path()):
        return ["no overlaps.json at %s (nothing to apply)" % overlaps_path()]
    mech = load_overlaps()
    files = [(p, _read_feature_file(p)) for p in _feature_files()]
    ids = {f["id"] for _, d in files for f in d.get("features", []) if isinstance(f.get("id"), str)}
    problems = ["overlaps.json names unknown feature %s (%s)" % (i, m)
                for m, lst in mech.items() for i in lst if i not in ids]
    peers = {}
    for m, lst in mech.items():
        for i in lst:
            peers.setdefault(i, set()).update(x for x in lst if x != i and x in ids)
    bodies = []
    for p, d in files:
        for f in d.get("features", []):
            fid = f.get("id")
            f["overlaps"] = sorted(peers.get(fid, ())) if isinstance(fid, str) else []
        bodies.append((p, json.dumps(d, indent=2, ensure_ascii=False) + "\n"))
    for p, body in bodies:
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(body)
    return problems


def _target_label():
    if config.MAIN is None:
        return "target"
    from . import registry
    try:
        return registry.entry(config.MAIN)["label"]
    except (KeyError, OSError, ValueError):
        return "target"


def _j(v):
    if isinstance(v, list):
        return ", ".join("`%s`" % x for x in v) if v else "—"
    if isinstance(v, dict):
        return "; ".join("%s: %s" % (k, ", ".join(map(str, x)) if isinstance(x, list) else x) for k, x in v.items()) or "—"
    return str(v) if v not in (None, "") else "—"


def _anchor(fid):
    return fid.replace(".", "").replace("_", "-").lower()


def build_inventory():
    t = _target_label()
    all_fs = load_all()
    fs = [f for f in all_fs if isinstance(f.get("id"), str)]
    cols = [(k, h) for k, h in (("value", "value"), ("target_status", t), ("difficulty", "difficulty"),
                                ("risk", "risk"), ("recommendation", "rec.")) if any(f.get(k) is not None for f in fs)]
    by_cat = defaultdict(list)
    for f in fs:
        by_cat[f.get("category", "other")].append(f)
    L = ["# Feature inventory", "",
         "Generated from `features/*.json` by `wbsd.py inventory` — edit the JSON, not this file. "
         "%d features across %d modules." % (len(fs), len({f.get('module') for f in fs})), ""]
    if cols:
        L.append("Columns: value 1-5 to %s · %s status · difficulty · risk · recommendation · confidence. "
                 "A dash means the record has no such judgement." % (t, t))
        L.append("")
    for f in all_fs:
        if not isinstance(f.get("id"), str):
            L.append("WARNING: skipped a record of module %s: id must be a string (got %r)" % (f.get("module"), f.get("id")))
            L.append("")
    L.append("## Index by category")
    L.append("")
    for cat in CATEGORIES:
        if not by_cat.get(cat):
            continue
        L.append("### %s" % cat)
        L.append("")
        L.append("| feature | module | %sconfidence |" % "".join(h + " | " for _, h in cols))
        L.append("|---|---|%s---|" % ("---|" * len(cols)))
        for f in sorted(by_cat[cat], key=lambda f: (-(f.get("value") or 0), f["id"])):
            L.append("| [%s](#%s) | %s | %s%s |" % (
                f.get("name"), _anchor(f["id"]), f.get("module"),
                "".join(_j(f.get(k)).replace("`", "") + " | " for k, _ in cols), f.get("confidence")))
        L.append("")
    L.append("## Details")
    L.append("")
    for cat in CATEGORIES:
        for f in sorted(by_cat.get(cat, []), key=lambda f: f["id"]):
            L.append('<a id="%s"></a>' % _anchor(f["id"]))
            L.append("### %s — %s (`%s`)" % (f.get("name"), f.get("module"), f["id"]))
            L.append("")
            L.append("**What it does:** %s" % _j(f.get("summary")))
            L.append("")
            L.append("**How it works:** %s" % _j(f.get("mechanics")))
            L.append("")
            for key, label in (("hooks", "Hooks"), ("scripts", "Scripts"), ("menus", "Menus"),
                               ("presentations", "Presentations"), ("mission_templates", "Mission templates"),
                               ("dialogs", "Dialogs"), ("slots", "Slots"), ("globals", "Globals"),
                               ("resources", "Module-specific resources"), ("native_relation", "Relation to Native"),
                               ("target_status", "%s status" % t), ("target_evidence", "%s evidence" % t),
                               ("conflicts", "Conflicts with %s" % t), ("difficulty", "Difficulty"), ("risk", "Risk"),
                               ("value", "Value"), ("recommendation", "Recommendation"), ("confidence", "Confidence"),
                               ("evidence", "Evidence"), ("overlaps", "Overlaps"), ("notes", "Notes")):
                if f.get(key) not in (None, "", [], {}):
                    L.append("- **%s:** %s" % (label, _j(f.get(key))))
            L.append("")
    return "\n".join(L)


def write_inventory():
    text = build_inventory()
    os.makedirs(config.ATLAS_DIR, exist_ok=True)
    path = os.path.join(config.ATLAS_DIR, "FEATURE_INVENTORY.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return path
