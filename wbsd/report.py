"""Auto module report: a structural map of one module, written to
ATLAS_DIR/auto/<slug>.md. It is a STARTING MAP for human/agent
investigation, not a verdict: everything here is derived mechanically."""
import os
import re
from collections import Counter, defaultdict

from . import analyze, categories, config, queries, registry

REPORTS = os.path.join(config.ATLAS_DIR, "auto")

THEMES = {
    "patrol": r"patrol", "caravan": r"caravan", "bandit/outlaw": r"bandit|outlaw|brigand",
    "mercenary": r"mercenar", "recruit": r"recruit", "prisoner/ransom": r"prisoner|ransom",
    "siege": r"siege|besieg", "formation": r"formation", "morale/rout": r"morale|rout",
    "trade/economy": r"trade|merchant|market|price|economy|tax", "diplomacy": r"treaty|alliance|truce|non-aggression|diplomac|embassy|envoy",
    "law/policy": r"\blaw\b|decree|policy|edict|council", "religion": r"relig|faith|church|temple|\bgods?\b|pagan|christian|priest",
    "culture": r"culture", "tournament": r"tournament|arena", "companion": r"companion",
    "marriage/romance": r"marri|courtship|romance|wedding", "fief/village": r"fief|village|manor|estate",
    "army/marshal": r"marshal|army|campaign", "rebellion/claimant": r"rebel|claimant|pretender|civil war|revolt",
    "event": r"\bevents?\b", "reputation/honor": r"honou?r|renown|reputation|prestige",
    "kingdom management": r"kingdom|realm|vassal|lord", "battle report": r"casualt|battle report|killed",
    "ships/naval": r"\bship|naval|sail|boat|fleet", "weather/season": r"weather|winter|season|snow|\brain\b|blizzard",
    "loot": r"loot", "training": r"train", "health/disease": r"disease|plague|wound|sick|heal",
    "food/supply": r"food|supply|starv|hunger",
}


def _text_hits(ix, native_texts):
    """Theme keyword hits over displayed text NOT already present in Native."""
    hits = Counter()
    examples = defaultdict(list)
    sources = []
    for kind in ("string", "qstr"):
        for name, t in ix.mod.texts.get(kind, {}).items():
            if t not in native_texts:
                sources.append((kind + ":" + name, t))
    for b in ix.mod.blocks:
        if b.kind in ("menu",) or (b.kind == "mopt" and b.part.endswith(":cond")) or (b.kind == "dlg" and b.part == "cond"):
            if b.meta.get("text", "") not in native_texts:
                sources.append((b.id, b.meta.get("text", "")))
    for sid, t in sources:
        tl = t.replace("_", " ")
        for theme, rx in THEMES.items():
            if re.search(rx, tl, re.I):
                hits[theme] += 1
                if len(examples[theme]) < 3:
                    examples[theme].append("%s \"%s\"" % (sid, tl[:70]))
    return hits, examples


def _named_block_hashes(ix, kinds):
    return {analyze.fingerprints(ix.mod, b)[1] for b in ix.mod.blocks if b.kind in kinds}


def build(slug):
    ix = queries.get(slug)
    nat = queries.get("native")
    m = ix.mod
    e = registry.entry(slug)
    L = []
    L.append("# Auto report: %s (`%s`)" % (m.label, slug))
    L.append("")
    L.append("Generated by `python3 wbsd/wbsd.py report %s`. Mechanical structure map — "
             "a starting point for investigation, not a verdict. Regenerate after the module changes." % slug)
    L.append("")
    L.append("## Basics")
    L.append("- path: `%s`  role: %s%s" % (e["path"], e["role"], ("  archive: `%s`" % e["archive"]) if e.get("archive") else ""))
    kinds = Counter(b.kind for b in m.blocks)
    L.append("- records: scripts %d, simple triggers %d, triggers %d, menus %d (+%d option blocks), presentations %d, "
             "mission templates %d (%d trigger blocks), dialog blocks %d, item-trigger blocks %d, scene-prop-trigger blocks %d"
             % (len(m.names.get("script", [])), kinds["strig"], kinds["trig"] // 2, len(m.names.get("menu", [])),
                kinds["mopt"], len(m.names.get("prsnt", [])), len(m.names.get("mt", [])), kinds["mst"],
                kinds["dlg"], kinds["itm"], kinds["spr"]))
    L.append("- tables: troops %d, items %d, party templates %d, parties %d, factions %d, scenes %d, scene props %d, globals %d, quests %d"
             % tuple(len(m.names.get(k, [])) for k in ("troop", "item", "pt", "party", "faction", "scene", "spr", "global", "quest")))
    L.append("- total bytecode statements: %d" % sum(len(b.stmts) for b in m.blocks))
    if m.errors:
        L.append("- PARSE ERRORS: %s" % m.errors)
    for n in m.notes:
        L.append("- note: %s" % n)
    if ix.unknown_ops:
        L.append("- **NON-VANILLA OPCODES** (engine-extension dependency): %s" % dict(ix.unknown_ops))
    else:
        L.append("- non-vanilla opcodes: none (pure vanilla-engine bytecode)")
    # lineage
    hs = queries._named_hashes(ix)
    rows = []
    for s in registry.slugs():
        if s == slug:
            continue
        hb = set(queries._named_hashes(queries.get(s)).values())
        rows.append((100.0 * sum(1 for v in hs.values() if v in hb) / max(len(hs), 1), s))
    rows.sort(reverse=True)
    L.append("- lineage (share of this module's scripts identical in another): " +
             ", ".join("%s %.0f%%" % (s, p) for p, s in rows[:5]))
    L.append("")
    # script delta vs native
    if slug != "native":
        hn = queries._named_hashes(nat)
        same = [n for n in hs if n in hn and hs[n] == hn[n]]
        mod_ = [n for n in hs if n in hn and hs[n] != hn[n]]
        new = [n for n in hs if n not in hn]
        gone = [n for n in hn if n not in hs]
        L.append("## Scripts vs Native")
        L.append("identical %d · modified %d · new %d · Native scripts absent %d" % (len(same), len(mod_), len(new), len(gone)))
        L.append("")
        L.append("### New scripts (not in Native) — stmts · callers · entry-point kinds · behaviour")
        L.append("")
        for n in sorted(new):
            b = m.block("script:" + n)
            cs = ix.callers_of(b.id)
            rts = ix.roots_of(b.id)
            rk = Counter(r.split(":", 1)[0] for r in rts)
            L.append("- `%s` %d · %d · %s · %s" % (n, len(b.stmts), len(cs),
                                                   ",".join("%s%d" % kv for kv in sorted(rk.items())) or "UNREACHED",
                                                   categories.summary(categories.profile(b), 3)))
        L.append("")
        L.append("### Modified Native scripts — stmts (this/Native) · similarity")
        L.append("")
        rws = []
        for n in mod_:
            b, nb = m.block("script:" + n), nat.mod.block("script:" + n)
            rws.append((analyze.jaccard(analyze.named_set(m, b), analyze.named_set(nat.mod, nb)), n, len(b.stmts), len(nb.stmts)))
        for sim, n, a, c in sorted(rws):
            L.append("- `%s` %d/%d · %.0f%%" % (n, a, c, 100 * sim))
        L.append("")
        L.append("### Native scripts absent here")
        L.append(", ".join("`%s`" % n for n in sorted(gone)) or "none")
        L.append("")
    # entry points
    nat_trig = _named_block_hashes(nat, ("strig",)) | _named_block_hashes(nat, ("trig",))
    L.append("## Periodic & event entry points")
    L.append("Simple triggers / triggers; `NATIVE` = byte-identical (named) to some Native trigger.")
    L.append("")
    for b in m.blocks:
        if b.kind not in ("strig", "trig") or not b.stmts:
            continue
        cs = [d.split(":", 1)[1] for d, _n, _b in ix.callees(b.id) if d]
        same = analyze.fingerprints(m, b)[1] in nat_trig
        L.append("- %s · %d stmts%s · calls %s · %s" % (queries.describe_bid(ix, b.id), len(b.stmts), " · NATIVE" if same else "",
                                                      ", ".join(dict.fromkeys(cs)) or "-", categories.summary(categories.profile(b), 3)))
    L.append("")
    # UI / missions
    for kind, label in (("mt", "Mission templates"), ("menu", "Menus"), ("prsnt", "Presentations")):
        names = m.names.get(kind, [])
        nn = set(nat.mod.names.get(kind, []))
        extra = [n for n in names if n not in nn]
        L.append("## %s not in Native (%d of %d)" % (label, len(extra), len(names)))
        L.append(", ".join("`%s`" % n for n in extra) or "none")
        L.append("")
    # globals & slots
    ng = set(nat.mod.names.get("global", []))
    eg = [g for g in m.names.get("global", []) if g not in ng]
    L.append("## Globals not in Native (%d)" % len(eg))
    L.append(", ".join(eg))
    L.append("")
    L.append("## Slots used here but not by Native (object: slot[accesses])")
    for obj in ("troop", "party", "faction", "scene", "party_template", "agent", "quest", "item", "team", "scene_prop", "player"):
        extra = sorted((s, len(r)) for (k, s), r in ix.slot_use.items() if k == obj and s is not None and (k, s) not in nat.slot_use)
        if extra:
            L.append("- %s: %s" % (obj, " ".join("%d[%d]" % x for x in extra)))
    L.append("")
    nt = set()
    for kind in ("string", "qstr"):
        nt.update(nat.mod.texts.get(kind, {}).values())
    nt.update(b.meta.get("text", "") for b in nat.mod.blocks if b.kind in ("menu", "mopt", "dlg"))
    hits, ex = _text_hits(ix, nt if slug != "native" else set())
    L.append("## Displayed-text theme hits in text NOT found in Native (strings, quick strings, menus, dialog lines)")
    for theme, n in hits.most_common():
        L.append("- %s: %d — e.g. %s" % (theme, n, "; ".join(ex[theme])))
    L.append("")
    return "\n".join(L)


def write(slug):
    os.makedirs(REPORTS, exist_ok=True)
    path = os.path.join(REPORTS, "%s.md" % slug)
    with open(path, "w") as fh:
        fh.write(build(slug))
    return path


def write_all(slugs=None):
    return [write(s) for s in (slugs or registry.slugs())]
