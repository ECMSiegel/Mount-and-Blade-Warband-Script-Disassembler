#!/usr/bin/env python3
"""Every named opcode must be corroborated by real corpus usage.

Two levels of corroboration, because the weaker one alone let a fabricated
comment through once already:

  1. EXISTENCE -- each opcode in EVIDENCE occurs somewhere in the shipped corpus
     (scripts.txt or simple_triggers.txt) with the operand count we claim.

  2. CITATION -- each evidence comment in wbops.py is parsed back out of the
     source and the cited statement is re-derived from the CITED script. If the
     comment says `game_start: 520(:v47, :v39, 18)`, then game_start must really
     contain a 520 statement that decodes to exactly that text. This is what
     makes an invented example a test failure rather than a plausible-looking
     lie, and it is why the examples are generated by gen_evidence.py.

Opcodes that take no operands (try_end/try_begin/else_try) have nothing to
decode. They must carry an EVIDENCE-STRUCTURAL marker naming their real proof --
the block-balance check in test_wbasm.py -- and are exempted from (2) by name
via wbops.STRUCTURAL. They are NOT skipped silently: a structural name with no
marker, or a marker for a name that is not structural, fails.

Run:  python3 -m unittest discover -s tests -v
"""
import os
import re
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import gen_evidence
import wbasm
import wbops
from wbsd import config
import _support

MODULE = os.path.join(config.MODULES_DIR, os.environ.get("WB_TEST_MODULE", "Native"))
WBOPS_PY = os.path.join(ROOT, "wbops.py")
FAILURES = []


def check(cond, label):
    if not cond:
        FAILURES.append(label)


# --- evidence comment parsing ----------------------------------------------

#: `NAME = 520   # game_start: 520(:v47, :v39, 18)`
_ASSIGN_RE = re.compile(r"^([A-Z][A-Z0-9_]*)\s*=\s*-?\d+\s*#\s*(.+?)\s*$")
#: `# EVIDENCE TRY_FOR_RANGE: game_start: 6(:v1, 0, trp620)`  (imported names)
_EVIDENCE_RE = re.compile(r"^#\s*EVIDENCE\s+([A-Z][A-Z0-9_]*)\s*:\s*(.+?)\s*$")
#: `# EVIDENCE-STRUCTURAL TRY_END: closes a block in ...`
_STRUCTURAL_RE = re.compile(r"^#\s*EVIDENCE-STRUCTURAL\s+([A-Z][A-Z0-9_]*)\s*:\s*(.+?)\s*$")
#: an evidence body: `<source>: <opcode>(<operands>)`
_CITATION_RE = re.compile(r"^(.+?):\s*((?:neg\||this_or_next\|)*\d+\(.*\))$")


def parse_evidence_comments(path=WBOPS_PY):
    """Return (cited, structural) maps parsed out of the wbops.py source."""
    cited, structural = {}, {}
    with open(path, "r") as fh:
        for line in fh:
            line = line.strip()
            m = _STRUCTURAL_RE.match(line)
            if m:
                structural[m.group(1)] = m.group(2)
                continue
            m = _EVIDENCE_RE.match(line)
            if m:
                cited[m.group(1)] = m.group(2)
                continue
            m = _ASSIGN_RE.match(line)
            if m:
                cited[m.group(1)] = m.group(2)
    return cited, structural


# --- tests ------------------------------------------------------------------

def _corpus_blocks():
    _support.require_module(MODULE)
    return list(gen_evidence.corpus(MODULE))


def test_every_name_has_evidence(cited, structural):
    """No entry may sit in EVIDENCE without a comment, and the structural
    exemption may only be claimed by the operand-less control-flow opcodes."""
    for name in wbops.EVIDENCE:
        has = name in cited or name in structural
        check(has, "%s has no evidence comment in wbops.py" % name)
        check(not (name in cited and name in structural),
              "%s claims both a decoded citation and a structural exemption" % name)
        if name in wbops.STRUCTURAL:
            check(name in structural,
                  "%s is declared structural but has no EVIDENCE-STRUCTURAL marker" % name)
        else:
            check(name not in structural,
                  "%s claims a structural exemption but is not in wbops.STRUCTURAL" % name)
    for name in structural:
        check(name in wbops.EVIDENCE,
              "EVIDENCE-STRUCTURAL marker for unknown name %s" % name)
    for name in wbops.STRUCTURAL:
        check(name in wbops.EVIDENCE, "STRUCTURAL names %s, which is not in EVIDENCE" % name)


def test_cited_statements_really_exist(blocks, cited):
    """THE anti-fabrication check: re-derive every cited example from the cited
    script and require an exact textual match."""
    by_source = {}
    for label, stmts in blocks:
        by_source.setdefault(label, []).extend(stmts)

    for name, body in sorted(cited.items()):
        if name not in wbops.EVIDENCE:
            continue                      # helper-constant comments, not evidence
        m = _CITATION_RE.match(body)
        if not m:
            FAILURES.append("%s: evidence comment is not a citation: %r" % (name, body))
            continue
        source, text = m.group(1), m.group(2)
        if source not in by_source:
            FAILURES.append("%s cites %r, which is not a script or trigger in the corpus"
                            % (name, source))
            continue
        opcode, arity = wbops.EVIDENCE[name]
        rendered = set()
        for st in by_source[source]:
            if st.opcode == opcode:
                rendered.add(gen_evidence.render_statement(st))
        if text not in rendered:
            sample = sorted(rendered)[:3]
            FAILURES.append(
                "%s: %r does NOT occur in %s. Real op-%d statements there: %s%s "
                "(regenerate with: python3 gen_evidence.py %d %d)"
                % (name, text, source, opcode,
                   ", ".join(sample) if sample else "none",
                   " ..." if len(rendered) > 3 else "", opcode, arity))


def test_named_ops_appear_in_corpus(blocks):
    """Each named opcode must occur in the shipped corpus with the operand
    count we claim for it."""
    seen = {}
    for _label, stmts in blocks:
        for st in stmts:
            seen.setdefault(st.opcode, set()).add(len(st.operands))
    for name, (opcode, arity) in wbops.EVIDENCE.items():
        check(opcode in seen, "%s (op %d) never appears in corpus" % (name, opcode))
        if opcode in seen:
            check(arity in seen[opcode],
                  "%s (op %d) never appears with %d operands; saw %s"
                  % (name, opcode, arity, sorted(seen[opcode])))


def test_operand_helpers():
    check(wbops.TRP(270) == 360287970189639950, "TRP(270) matches troop 270")
    check(wbops.SKL(15) == 1369094286720630799, "SKL(15) matches skill 15")
    check(wbops.SCRIPT(585) == 936748722493063753, "SCRIPT(585) matches script 585")
    check(wbops.PARTY(0) == 648518346341351424, "PARTY(0) matches party 0")
    check(wbops.V(0) == 1224979098644774912, "V(0) matches local var 0")


def test_render_operand_masks():
    """gen_evidence is now load-bearing for the citation check, so its operand
    rendering is pinned to the encodings wbasm proved from shipped bytecode."""
    cases = [(wbops.REG(40), "reg40"), (wbops.GVAR(1206), "$g1206"),
             (wbops.STR(4328), "str4328"), (wbops.ITM(81), "itm81"),
             (wbops.TRP(270), "trp270"), (wbops.PARTY(0), "p0"),
             (wbops.SCRIPT(585), "script585"), (wbops.V(2), ":v2"),
             (wbops.SKL(15), "skl15"), (wbasm.enc(22, 380), "qstr380"),
             (7, "7"), (-1, "-1")]
    for operand, want in cases:
        got = gen_evidence.render_operand(operand)
        check(got == want, "render_operand(%d) = %r, want %r" % (operand, got, want))


def test_statement_builder():
    st = wbops.S(wbops.TROOP_RAISE_SKILL, wbops.TRP(0), wbops.SKL(15), 1)
    check(st.opcode == 1521, "builder sets opcode")
    check(st.tokens() == ["1521", "3", "360287970189639680", "1369094286720630799", "1"],
          "builder emits the exact book-trigger statement")
    neg = wbops.S(wbops.EQ, 1, 2, flags=wbasm.OP_NEG)
    check(neg.tokens()[0] == "2147483679", "neg| flag encodes into the opcode")


class WbopsTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.cited, cls.structural = parse_evidence_comments()

    def _run(self, fn, *args):
        before = len(FAILURES)
        fn(*args)
        self.assertEqual(FAILURES[before:], [])

    def test_every_name_has_evidence(self):
        self._run(test_every_name_has_evidence, self.cited, self.structural)

    # The citations were generated from Native, so they can only be re-derived
    # against Native.
    @unittest.skipUnless(os.path.basename(MODULE) == "Native", "citations are from Native; needs WB_TEST_MODULE=Native")
    def test_cited_statements_really_exist(self):
        self._run(test_cited_statements_really_exist, _corpus_blocks(), self.cited)

    @unittest.skipUnless(os.path.basename(MODULE) == "Native", "citations are from Native; needs WB_TEST_MODULE=Native")
    def test_named_ops_appear_in_corpus(self):
        self._run(test_named_ops_appear_in_corpus, _corpus_blocks())


_support.add_tests(WbopsTests, (test_operand_helpers, test_render_operand_masks, test_statement_builder), FAILURES)


def main():
    cited, structural = parse_evidence_comments()
    test_every_name_has_evidence(cited, structural)
    if os.path.basename(MODULE) == "Native":
        blocks = _corpus_blocks()
        test_cited_statements_really_exist(blocks, cited)
        test_named_ops_appear_in_corpus(blocks)
    test_operand_helpers()
    test_render_operand_masks()
    test_statement_builder()
    if FAILURES:
        print("FAILED: %d" % len(FAILURES))
        for f in FAILURES:
            print("  - %s" % f)
        return 1
    print("verified %d named opcodes (%d decoded citations, %d structural)"
          % (len(wbops.EVIDENCE), len(wbops.EVIDENCE) - len(wbops.STRUCTURAL),
             len(wbops.STRUCTURAL)))
    print("all green")
    return 0


if __name__ == "__main__":
    sys.exit(main())
